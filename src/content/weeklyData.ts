export function getWeekData(week: number): WeekData | null {
  const clampedWeek = Math.min(Math.max(week, 4), 40);
  // Find exact or nearest week
  if (weeklyData[clampedWeek]) return weeklyData[clampedWeek];
  // Find closest available week
  const available = Object.keys(weeklyData).map(Number).sort((a, b) => a - b);
  const closest = available.reduce((prev, curr) =>
    Math.abs(curr - clampedWeek) < Math.abs(prev - clampedWeek) ? curr : prev,
  );
  return weeklyData[closest] ?? null;
}
